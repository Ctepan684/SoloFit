import { $, state, closeAllSheets } from "./state.js";
import { initFood } from "./food.js";
import { initWorkout } from "./workout.js";
import { initAuth } from "./auth.js";

function showErr(where, err) {
  const box = document.createElement("div");
  box.style.cssText = "position:fixed;top:10px;left:10px;right:10px;z-index:9999;background:#b00020;color:#fff;padding:12px;border-radius:12px;font-size:13px;";
  box.textContent = `Ошибка в ${where}: ${err.message}`;
  document.body.appendChild(box);
}

$("today").textContent = state.now.toLocaleDateString("ru-RU", {
  weekday: "long",
  day: "numeric",
  month: "long"
});

$("scrim").addEventListener("click", closeAllSheets);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeAllSheets();
});

const tabs = document.querySelectorAll("[data-tab]");
tabs.forEach((t) => {
  t.addEventListener("click", () => {
    const name = t.dataset.tab;
    tabs.forEach((x) => x.setAttribute("aria-selected", String(x === t)));
    $("view-food").classList.toggle("active", name === "food");
    $("view-train").classList.toggle("active", name === "train");
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
});

try { initFood(); } catch (e) { showErr("food.js", e); }
try { initWorkout(); } catch (e) { showErr("workout.js", e); }
try { initAuth(); } catch (e) { showErr("auth.js", e); }
