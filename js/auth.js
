import { SUPABASE_URL, SUPABASE_KEY, GOAL_LABELS, ACTIVITY_MAP } from "./data.js";
import { $, state, loadDb, calcGoal, closeAllSheets } from "./state.js";
import { renderFood } from "./food.js";
import { renderWorkout } from "./workout.js";

let sb = null;

function setMsg(id, text, kind) {
  const el = $(id);
  if (!el) return;
  el.textContent = text;
  el.className = "msg show " + kind;
}
function clearMsg(id) {
  const el = $(id);
  if (!el) return;
  el.textContent = "";
  el.className = "msg";
}
function setBusy(btnId, busy, idleText) {
  const b = $(btnId);
  b.disabled = busy;
  b.textContent = busy ? "Подождите..." : idleText;
}
function validEmail(s) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(s);
}
function humanError(err) {
  const m = (err?.message || "").toLowerCase();
  if (m.includes("invalid login")) return "Неверная почта или пароль.";
  if (m.includes("email not confirmed")) return "Подтвердите почту: мы отправили письмо со ссылкой.";
  if (m.includes("already registered") || m.includes("already been registered")) return "Этот email уже зарегистрирован. Попробуйте войти.";
  if (m.includes("password") && m.includes("6")) return "Пароль должен быть не короче 6 символов.";
  if (m.includes("rate limit") || m.includes("too many")) return "Слишком много попыток. Подождите немного.";
  if (m.includes("network") || m.includes("failed to fetch")) return "Нет связи с сервером. Проверьте интернет.";
  return "Что-то пошло не так. Попробуйте ещё раз.";
}

function showOnboardingScreen(viewId) {
  $("appWrap").classList.add("hidden");
  $("tabbar").classList.add("hidden");
  $("onboardingWrap").classList.remove("hidden");
  ["authView", "goalView", "metricsView", "activityView"].forEach((id) => {
    $(id).classList.toggle("hidden", id !== viewId);
  });
  window.scrollTo({ top: 0 });
}

function syncOnboardingUI() {
  document.querySelectorAll(".goal-opt").forEach((b) =>
    b.classList.toggle("selected", b.dataset.goal === state.draft.goal)
  );
  $("inputHeight").value = state.draft.height || "";
  $("inputWeight").value = state.draft.weight || "";
  document.querySelectorAll(".act-opt").forEach((b) =>
    b.classList.toggle("selected", b.dataset.activity === state.draft.activity)
  );
}

function showApp(user) {
  state.user = user;
  const meta = user.user_metadata || {};
  state.goal = calcGoal(meta);
  loadDb();

  $("onboardingWrap").classList.add("hidden");
  $("appWrap").classList.remove("hidden");
  $("tabbar").classList.remove("hidden");

  const name = meta.name || (user.email ? user.email.split("@")[0] : "Профиль");
  $("profileName").textContent = name;
  $("stripGoal").textContent = GOAL_LABELS[meta.goal] || "—";
  $("stripKcal").textContent = state.goal.kcal + " ккал";
  $("profGoal").textContent = GOAL_LABELS[meta.goal] || "—";
  $("profAct").textContent = ACTIVITY_MAP[meta.activity]?.label || "—";
  $("profBody").textContent = `${meta.height || "—"} см / ${meta.weight || "—"} кг`;
  $("profKcal").textContent = state.goal.kcal + " ккал";

  renderFood();
  renderWorkout();
}

function routeUser(user) {
  state.user = user || null;
  if (!user) return showOnboardingScreen("authView");

  const meta = user.user_metadata || {};
  state.draft = {
    goal: meta.goal || "",
    height: meta.height || "",
    weight: meta.weight || "",
    activity: meta.activity || ""
  };

  syncOnboardingUI();
  if (!state.draft.goal || !GOAL_LABELS[state.draft.goal]) return showOnboardingScreen("goalView");
  if (!state.draft.height || !state.draft.weight) return showOnboardingScreen("metricsView");
  if (!state.draft.activity || !ACTIVITY_MAP[state.draft.activity]) return showOnboardingScreen("activityView");
  showApp(user);
}

export function initAuth() {
  if (window.supabase?.createClient) {
    sb = window.supabase.createClient(SUPABASE_URL, SUPABASE_KEY);
  } else {
    setMsg("loginMsg", "Не загрузилась библиотека Supabase. Проверьте интернет.", "err");
    setMsg("signupMsg", "Не загрузилась библиотека Supabase. Проверьте интернет.", "err");
  }

  const selectTab = (which) => {
    const login = which === "login";
    $("tabLogin").setAttribute("aria-selected", String(login));
    $("tabSignup").setAttribute("aria-selected", String(!login));
    $("formLogin").classList.toggle("hidden", !login);
    $("formSignup").classList.toggle("hidden", login);
    clearMsg("loginMsg"); clearMsg("signupMsg");
  };
  $("tabLogin").addEventListener("click", () => selectTab("login"));
  $("tabSignup").addEventListener("click", () => selectTab("signup"));

  $("formLogin").addEventListener("submit", async (e) => {
    e.preventDefault();
    clearMsg("loginMsg");
    if (!sb) return setMsg("loginMsg", "Supabase не загрузился.", "err");
    const email = $("loginEmail").value.trim();
    const password = $("loginPassword").value;
    if (!validEmail(email)) return setMsg("loginMsg", "Введите корректный email.", "err");
    if (!password) return setMsg("loginMsg", "Введите пароль.", "err");
    setBusy("loginBtn", true, "Войти");
    const res = await sb.auth.signInWithPassword({ email, password });
    setBusy("loginBtn", false, "Войти");
    if (res.error) return setMsg("loginMsg", humanError(res.error), "err");
    routeUser(res.data.user);
  });

  $("formSignup").addEventListener("submit", async (e) => {
    e.preventDefault();
    clearMsg("signupMsg");
    if (!sb) return setMsg("signupMsg", "Supabase не загрузился.", "err");
    const name = $("signupName").value.trim();
    const email = $("signupEmail").value.trim();
    const password = $("signupPassword").value;
    if (!name) return setMsg("signupMsg", "Введите имя.", "err");
    if (!validEmail(email)) return setMsg("signupMsg", "Введите корректный email.", "err");
    if (password.length < 6) return setMsg("signupMsg", "Пароль должен быть не короче 6 символов.", "err");
    setBusy("signupBtn", true, "Создать аккаунт");
    const res = await sb.auth.signUp({ email, password, options: { data: { name } } });
    setBusy("signupBtn", false, "Создать аккаунт");
    if (res.error) return setMsg("signupMsg", humanError(res.error), "err");
    if (res.data.session) return routeUser(res.data.user);
    setMsg("signupMsg", `Аккаунт создан. Подтвердите почту ${email} и войдите.`, "ok");
    $("formSignup").reset();
  });

  document.querySelectorAll(".goal-opt").forEach((btn) => {
    btn.addEventListener("click", () => {
      state.draft.goal = btn.dataset.goal;
      syncOnboardingUI();
      showOnboardingScreen("metricsView");
      setTimeout(() => $("inputHeight").focus(), 60);
    });
  });

  $("metricsBack").addEventListener("click", () => showOnboardingScreen("goalView"));
  $("formMetrics").addEventListener("submit", (e) => {
    e.preventDefault();
    clearMsg("metricsMsg");
    const h = parseFloat($("inputHeight").value);
    const w = parseFloat($("inputWeight").value);
    if (!h || h < 100 || h > 250) return setMsg("metricsMsg", "Рост от 100 до 250 см.", "err");
    if (!w || w < 30 || w > 250) return setMsg("metricsMsg", "Вес от 30 до 250 кг.", "err");
    state.draft.height = Math.round(h);
    state.draft.weight = Math.round(w * 10) / 10;
    syncOnboardingUI();
    showOnboardingScreen("activityView");
  });

  document.querySelectorAll(".act-opt").forEach((btn) => {
    btn.addEventListener("click", () => {
      clearMsg("activityMsg");
      state.draft.activity = btn.dataset.activity;
      syncOnboardingUI();
    });
  });

  $("activityBack").addEventListener("click", () => showOnboardingScreen("metricsView"));
  $("activitySave").addEventListener("click", async () => {
    clearMsg("activityMsg");
    if (!state.draft.activity || !ACTIVITY_MAP[state.draft.activity]) {
      return setMsg("activityMsg", "Выберите один из 5 уровней активности.", "err");
    }
    setBusy("activitySave", true, "Запустить SoloFit");
    const res = await sb.auth.updateUser({ data: state.draft });
    setBusy("activitySave", false, "Запустить SoloFit");
    if (res.error) return setMsg("activityMsg", "Ошибка сохранения: " + res.error.message, "err");
    showApp(res.data.user);
  });

  $("openProfile").addEventListener("click", () => {
    $("sheet").hidden = true;
    $("profileSheet").hidden = false;
    $("scrim").hidden = false;
  });
  $("closeProfile").addEventListener("click", closeAllSheets);
  $("editParamsBtn").addEventListener("click", () => {
    closeAllSheets();
    syncOnboardingUI();
    showOnboardingScreen("goalView");
  });
  $("logoutBtn").addEventListener("click", async () => {
    closeAllSheets();
    if (sb) await sb.auth.signOut();
    routeUser(null);
    selectTab("login");
  });

  if (sb) {
    sb.auth.onAuthStateChange((event, session) => {
      if (session?.user) routeUser(session.user);
      else if (event === "SIGNED_OUT") routeUser(null);
    });
    sb.auth.getSession().then((r) => routeUser(r.data?.session?.user || null));
  }
}
